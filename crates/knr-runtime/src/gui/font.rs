/// Returns the 8x8 bitmap slice for a given ASCII character.
/// Characters outside printable ASCII [32..=126] default to '?' (index 31 in table).
#[inline]
pub fn get_glyph(c: char) -> &'static [u8; 8] {
    let code = c as usize;
    if (32..=126).contains(&code) {
        &FONT_8X8[code - 32]
    } else {
        &FONT_8X8[63 - 32] // '?'
    }
}

/// Computes the pixel dimensions `(width, height)` of a string given a font scale factor.
/// Supports multi-line strings separated by `\n`.
pub fn measure_text(text: &str, scale: u32) -> (u32, u32) {
    let s = scale.max(1);
    let char_w = 8 * s;
    let line_h = 8 * s;

    let mut max_chars = 0;
    let mut lines = 0;

    for line in text.split('\n') {
        lines += 1;
        let c_len = line.chars().filter(|&c| c != '\r').count();
        if c_len > max_chars {
            max_chars = c_len;
        }
    }

    if lines == 0 {
        lines = 1;
    }

    (max_chars as u32 * char_w, lines as u32 * line_h)
}
